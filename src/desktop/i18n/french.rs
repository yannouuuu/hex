#[cfg(test)]
mod tests {
    use super::TRANSLATIONS;

    #[test]
    fn french_covers_every_english_string_in_order() {
        let english: Vec<&str> = super::super::TRANSLATIONS
            .iter()
            .map(|(english, _)| *english)
            .collect();
        let french: Vec<&str> = TRANSLATIONS.iter().map(|(english, _)| *english).collect();
        assert_eq!(french.len(), english.len(), "the tables differ in length");
        for (index, (french, english)) in french.iter().zip(&english).enumerate() {
            assert_eq!(french, english, "entry {index} is out of order");
        }
    }

    #[test]
    fn french_keys_are_unique_and_keep_their_placeholders() {
        let mut seen = std::collections::HashSet::new();
        for (english, french) in TRANSLATIONS {
            assert!(seen.insert(english), "duplicate key {english:?}");
            if english.contains("{}") {
                assert!(
                    french.contains("{}"),
                    "translation of {english:?} lost its placeholder: {french:?}"
                );
            }
            let names = english
                .split('{')
                .skip(1)
                .filter_map(|part| part.split_once('}'))
                .map(|(name, _)| name);
            for name in names {
                assert!(
                    french.contains(&format!("{{{name}}}")),
                    "translation of {english:?} lost {{{name}}}: {french:?}"
                );
            }
        }
    }

    #[test]
    fn french_strings_are_complete() {
        for (english, french) in TRANSLATIONS {
            assert!(!french.is_empty(), "{english:?} has no French");
            assert_eq!(french.trim(), *french, "{english:?} has outer whitespace");
            assert!(!french.contains("  "), "{english:?} has a double space");
        }
    }

    #[test]
    fn french_uses_non_breaking_spaces() {
        for (english, french) in TRANSLATIONS {
            for punctuation in [';', ':', '?', '!', '%'] {
                assert!(
                    !french.contains(&format!(" {punctuation}")),
                    "{english:?} has a breakable space before {punctuation}"
                );
            }
            for quote in ['«', '»'] {
                let spaced = if quote == '«' {
                    format!("{quote} ")
                } else {
                    format!(" {quote}")
                };
                assert!(
                    !french.contains(&spaced),
                    "{english:?} has a breakable space inside guillemets"
                );
            }
        }
    }
}
